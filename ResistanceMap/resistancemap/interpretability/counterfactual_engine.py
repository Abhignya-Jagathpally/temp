class CausalEffectEstimator:
    """Estimate treatment effects from the learned structural causal model.

    The causal fusion layer in ResistanceMap encodes the hierarchy:
        genetic -> epigenetic -> transcriptomic -> proteomic

    We can perform do-calculus interventions (Pearl, 2009) on any layer
    to estimate the causal effect of treatments.

    Implements:
    - ATE: Average Treatment Effect = E[Y(1)] - E[Y(0)]
    - CATE: Conditional ATE = E[Y(1) - Y(0) | X = x] for subgroups
    - ITE: Individual Treatment Effect = Y_i(1) - Y_i(0) for each patient

    Following Shalit et al. (2017) "Estimating individual treatment effect:
    generalization bounds and algorithms" (ICML).

    Args:
        model: ResistanceMap model with causal fusion layer.
        config: CounterfactualConfig.
    """

    def __init__(
        self,
        model: nn.Module,
        config: Optional[CounterfactualConfig] = None,
    ) -> None:
        self.model = model
        self.config = config or CounterfactualConfig()
        self.device = torch.device(self.config.device)
        self.model.to(self.device)
        self.model.eval()

    def estimate_ate(
        self,
        patient_states: Tensor,
        t_span: Tensor,
        treatment_drug: int,
        treatment_dose: float,
        control_drug: Optional[int] = None,
        control_dose: float = 0.0,
    ) -> Dict[str, Any]:
        """Estimate the Average Treatment Effect (ATE).

        ATE = E[Y(treatment)] - E[Y(control)]

        Uses the Neural ODE to simulate both treated and control trajectories
        for each patient, then averages the difference.

        Args:
            patient_states: (N, D) tensor of patient initial states.
            t_span: Time span for simulation.
            treatment_drug: Drug ID for treatment arm.
            treatment_dose: Dose for treatment arm.
            control_drug: Drug ID for control arm (None = no treatment).
            control_dose: Dose for control arm.

        Returns:
            Dict with 'ate', 'ate_ci', 'ite' (individual effects),
            and 'treated_outcomes', 'control_outcomes'.
        """
        N = patient_states.shape[0]
        cf_gen = CounterfactualTrajectoryGenerator(self.model, config=self.config)

        treated_outcomes = np.zeros(N)
        control_outcomes = np.zeros(N)

        for i in range(N):
            x0_i = patient_states[i]

            # Treated trajectory
            traj_t = cf_gen.simulate_trajectory(x0_i, t_span, treatment_drug, treatment_dose)
            treated_outcomes[i] = float(self._compute_outcome(traj_t[-1:]))

            # Control trajectory
            traj_c = cf_gen.simulate_trajectory(x0_i, t_span, control_drug, control_dose)
            control_outcomes[i] = float(self._compute_outcome(traj_c[-1:]))

        ite = treated_outcomes - control_outcomes
        ate = float(np.mean(ite))

        # Bootstrap confidence interval
        n_bootstrap = 1000
        boot_ates = np.zeros(n_bootstrap)
        for b in range(n_bootstrap):
            idx = np.random.choice(N, size=N, replace=True)
            boot_ates[b] = np.mean(ite[idx])
        ci_lo = float(np.percentile(boot_ates, 2.5))
        ci_hi = float(np.percentile(boot_ates, 97.5))

        return {
            "ate": ate,
            "ate_ci": (ci_lo, ci_hi),
            "ite": ite,
            "treated_outcomes": treated_outcomes,
            "control_outcomes": control_outcomes,
        }

    def estimate_cate(
        self,
        patient_states: Tensor,
        t_span: Tensor,
        treatment_drug: int,
        treatment_dose: float,
        subgroup_labels: np.ndarray,
        control_drug: Optional[int] = None,
        control_dose: float = 0.0,
    ) -> CausalEffectResult:
        """Estimate Conditional Average Treatment Effect (CATE) per subgroup.

        CATE_g = E[Y(1) - Y(0) | G = g]

        Subgroups might be defined by genetic subtypes, disease stage, or
        prior treatment history.

        Args:
            patient_states: (N, D) tensor of patient states.
            t_span: Time span.
            treatment_drug: Drug ID for treatment.
            treatment_dose: Dose for treatment.
            subgroup_labels: (N,) array of subgroup assignments.
            control_drug: Drug ID for control.
            control_dose: Dose for control.

        Returns:
            CausalEffectResult with ATE, CATE, ITE, and CIs.
        """
        ate_result = self.estimate_ate(
            patient_states, t_span, treatment_drug, treatment_dose,
            control_drug, control_dose,
        )
        ite = ate_result["ite"]

        unique_groups = sorted(set(subgroup_labels))
        cate = {}
        cis = {"ate": ate_result["ate_ci"]}

        for g in unique_groups:
            mask = subgroup_labels == g
            group_ite = ite[mask]
            cate[str(g)] = float(np.mean(group_ite))

            # Bootstrap CI for this subgroup
            n_boot = 1000
            n_g = mask.sum()
            boot = np.zeros(n_boot)
            for b in range(n_boot):
                idx = np.random.choice(n_g, size=n_g, replace=True)
                boot[b] = np.mean(group_ite[idx])
            cis[str(g)] = (float(np.percentile(boot, 2.5)),
                           float(np.percentile(boot, 97.5)))

        return CausalEffectResult(
            ate=ate_result["ate"],
            cate=cate,
            ite=ite,
            confidence_intervals=cis,
            subgroup_labels=[str(g) for g in unique_groups],
        )

    def do_intervention(
        self,
        x0: Tensor,
        t_span: Tensor,
        layer_name: str,
        intervention_values: Tensor,
    ) -> Tensor:
        """Perform a do-calculus intervention on the causal fusion layer.

        Implements do(layer = value) by clamping the specified layer's output
        to the intervention values during forward pass.

        The causal hierarchy is: genetic -> epigenetic -> transcriptomic -> proteomic.
        Intervening on an upstream layer propagates effects downstream.

        Args:
            x0: Initial state.
            t_span: Time span.
            layer_name: Name of the causal layer to intervene on.
            intervention_values: Values to clamp the layer to.

        Returns:
            Intervened trajectory tensor.
        """
        warnings.warn(_LATENT_CLAMP_WARNING, DeprecationWarning, stacklevel=2)
        if x0.dim() == 1:
            x0 = x0.unsqueeze(0)
        x0 = x0.to(self.device)
        t_span = t_span.to(self.device)
        intervention_values = intervention_values.to(self.device)

        # Create a modified model with the intervention
        model_copy = copy.deepcopy(self.model)

        # Register a forward hook on the target layer to clamp output
        target_layer = None
        for name, module in model_copy.named_modules():
            if layer_name in name:
                target_layer = module
                break

        if target_layer is None:
            raise ValueError(
                f"Layer '{layer_name}' not found. Available: "
                f"{[n for n, _ in model_copy.named_modules()]}"
            )

        def clamp_hook(module, input, output):
            return intervention_values.expand_as(output)

        handle = target_layer.register_forward_hook(clamp_hook)

        # Simulate with intervened model
        try:
            if hasattr(model_copy, "solve"):
                trajectory = model_copy.solve(x0, t_span)
            else:
                trajectory = self._euler_solve(model_copy, x0, t_span)
        finally:
            handle.remove()

        return trajectory.detach().cpu()

    def _euler_solve(self, model: nn.Module, x0: Tensor, t_eval: Tensor) -> Tensor:
        traj = [x0]
        x = x0
        for i in range(1, len(t_eval)):
            dt = (t_eval[i] - t_eval[i - 1]).item()
            dxdt = model.ode_func(t_eval[i - 1], x)
            x = x + dt * dxdt
            traj.append(x)
        return torch.stack(traj)

    def _compute_outcome(self, x: Tensor) -> Tensor:
        if x.dim() == 3:
            x = x.squeeze(0)
        if hasattr(self.model, "predict"):
            with torch.no_grad():
                return self.model.predict(x).mean()
        if hasattr(self.model, "classifier"):
            with torch.no_grad():
                return torch.sigmoid(self.model.classifier(x)).mean()
        return x.norm(dim=-1).mean()


