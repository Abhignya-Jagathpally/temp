# ---------------------------------------------------------------------------
# Counterfactual Trajectory Generator
# ---------------------------------------------------------------------------

class CounterfactualTrajectoryGenerator:
    """Generate counterfactual trajectories under alternative drug interventions.

    The core idea is that the Neural ODE models patient dynamics as:
        dx/dt = f(x, t) + g(x, drug)
    where f captures autonomous disease dynamics and g captures drug effects.
    By changing the drug term g, we can simulate what would have happened under
    a different treatment without retraining the model.

    Key capabilities:
    - Simulate trajectories under alternative drug interventions
    - Find the MINIMAL intervention that reverses resistance
    - Compute the resistance reversal dose (minimum dose to flip attractor)
    - Find the optimal intervention timing

    Following Bica et al. (2020) "Estimating counterfactual treatment outcomes
    over time using longitudinal data" (NeurIPS) and Seedat et al. (2022)
    "Continuous-time modeling of counterfactual outcomes" (ICML).

    Args:
        model: ResistanceMap Neural ODE model.
        drug_encoder: Module mapping drug identity + dose to intervention vector.
        config: CounterfactualConfig instance.
    """

    def __init__(
        self,
        model: nn.Module,
        drug_encoder: Optional[nn.Module] = None,
        config: Optional[CounterfactualConfig] = None,
    ) -> None:
        self.model = model
        self.drug_encoder = drug_encoder
        self.config = config or CounterfactualConfig()
        self.device = torch.device(self.config.device)
        self.model.to(self.device)
        self.model.eval()

    # ------------------------------------------------------------------
    # Core: simulate counterfactual trajectory
    # ------------------------------------------------------------------

    def simulate_trajectory(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_id: Optional[int] = None,
        drug_dose: float = 0.0,
        drug_start_time: Optional[float] = None,
        drug_end_time: Optional[float] = None,
    ) -> Tensor:
        """Simulate a trajectory under a specified drug intervention.

        Integrates the modified ODE:
            dx/dt = f(x, t) + drug_effect(x, drug_id, dose) * I(t in [t_start, t_end])

        where I is the indicator function for the treatment window.

        Args:
            x0: Initial state, shape (batch, D) or (D,).
            t_span: Time evaluation points, shape (T,).
            drug_id: Integer drug identifier. None means no drug.
            drug_dose: Drug dosage level.
            drug_start_time: When drug administration begins.
            drug_end_time: When drug administration ends.

        Returns:
            Trajectory tensor of shape (T, batch, D) or (T, D).
        """
        squeeze = x0.dim() == 1
        if squeeze:
            x0 = x0.unsqueeze(0)
        x0 = x0.to(self.device)
        t_span = t_span.to(self.device)

        # Build the drug effect function
        drug_effect_fn = self._build_drug_effect(drug_id, drug_dose)
        t_start = drug_start_time if drug_start_time is not None else t_span[0].item()
        t_end = drug_end_time if drug_end_time is not None else t_span[-1].item()

        # Integrate with modified dynamics
        trajectory = self._integrate_with_intervention(
            x0, t_span, drug_effect_fn, t_start, t_end
        )

        if squeeze:
            trajectory = trajectory.squeeze(1)
        return trajectory.detach().cpu()

    def generate_counterfactuals(
        self,
        x0: Tensor,
        t_span: Tensor,
        factual_drug: Optional[int],
        factual_dose: float,
        alternative_drugs: List[Tuple[Optional[int], float]],
        drug_names: Optional[List[str]] = None,
    ) -> CounterfactualResult:
        """Generate factual and counterfactual trajectories for comparison.

        Args:
            x0: Initial patient state.
            t_span: Time evaluation points.
            factual_drug: The drug actually administered (None for no treatment).
            factual_dose: Actual dosage.
            alternative_drugs: List of (drug_id, dose) tuples for counterfactual scenarios.
            drug_names: Optional human-readable names for drugs.

        Returns:
            CounterfactualResult with all trajectories and outcomes.
        """
        t_span_dev = t_span.to(self.device)

        # Factual trajectory
        factual_traj = self.simulate_trajectory(x0, t_span, factual_drug, factual_dose)
        factual_outcome = self._compute_outcome(factual_traj[-1:])

        # Counterfactual trajectories
        cf_trajectories = {}
        cf_outcomes = {}
        intervention_details = {}

        for i, (drug_id, dose) in enumerate(alternative_drugs):
            name = drug_names[i] if drug_names else f"drug_{drug_id}_dose_{dose:.1f}"
            cf_traj = self.simulate_trajectory(x0, t_span, drug_id, dose)
            cf_outcome = self._compute_outcome(cf_traj[-1:])

            cf_trajectories[name] = cf_traj.numpy()
            cf_outcomes[name] = float(cf_outcome)
            intervention_details[name] = {"drug_id": drug_id, "dose": dose}

        return CounterfactualResult(
            factual_trajectory=factual_traj.numpy(),
            counterfactual_trajectories=cf_trajectories,
            factual_outcome=float(factual_outcome),
            counterfactual_outcomes=cf_outcomes,
            intervention_details=intervention_details,
        )

    # ------------------------------------------------------------------
    # Minimal intervention search
    # ------------------------------------------------------------------

    def find_minimal_intervention(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_id: int,
        target_outcome: float = 0.0,
    ) -> Dict[str, Any]:
        """Find the minimum drug dose that reverses resistance.

        Uses binary search over dose levels to find the smallest dose that
        pushes the outcome below the resistance threshold.

        The "resistance reversal dose" is clinically meaningful: it tells
        the oncologist the minimum effective dose.

        Args:
            x0: Initial patient state.
            t_span: Time span.
            drug_id: Drug to administer.
            target_outcome: Target outcome threshold (below = sensitive).

        Returns:
            Dict with 'minimal_dose', 'outcome_at_dose', 'dose_response_curve'.
        """
        lo = self.config.min_intervention_strength
        hi = self.config.max_intervention_strength
        n_eval = self.config.dose_search_resolution

        # First, evaluate dose-response curve
        doses = np.linspace(lo, hi, n_eval)
        outcomes = np.zeros(n_eval)

        for i, dose in enumerate(doses):
            traj = self.simulate_trajectory(x0, t_span, drug_id, float(dose))
            outcomes[i] = float(self._compute_outcome(traj[-1:]))

        # Find crossing point
        below_target = outcomes <= target_outcome
        if not below_target.any():
            return {
                "minimal_dose": None,
                "outcome_at_dose": None,
                "dose_response_curve": (doses, outcomes),
                "message": "No dose in range reverses resistance.",
            }

        # Binary search for precise crossing
        first_below = np.argmax(below_target)
        if first_below == 0:
            lo_dose, hi_dose = lo, doses[0]
        else:
            lo_dose, hi_dose = doses[first_below - 1], doses[first_below]

        for _ in range(20):  # 20 iterations of bisection
            mid = (lo_dose + hi_dose) / 2
            traj = self.simulate_trajectory(x0, t_span, drug_id, mid)
            out = float(self._compute_outcome(traj[-1:]))
            if out <= target_outcome:
                hi_dose = mid
            else:
                lo_dose = mid

        minimal_dose = hi_dose
        traj = self.simulate_trajectory(x0, t_span, drug_id, minimal_dose)
        final_outcome = float(self._compute_outcome(traj[-1:]))

        return {
            "minimal_dose": minimal_dose,
            "outcome_at_dose": final_outcome,
            "dose_response_curve": (doses.tolist(), outcomes.tolist()),
        }

    # ------------------------------------------------------------------
    # Time-optimal intervention
    # ------------------------------------------------------------------

    def find_optimal_intervention_time(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_id: int,
        drug_dose: float,
        target_outcome: float = 0.0,
    ) -> Dict[str, Any]:
        """Find the latest time at which intervention still prevents resistance.

        This answers the critical clinical question: "How long can we wait
        before it's too late to intervene?"

        We simulate trajectories where the drug is administered starting at
        different times and find the latest start time that still achieves
        the target outcome.

        Args:
            x0: Initial patient state.
            t_span: Full time span.
            drug_id: Drug to use.
            drug_dose: Dose to administer.
            target_outcome: Threshold below which the patient is "sensitive."

        Returns:
            Dict with 'latest_effective_time', 'time_outcome_curve',
            and 'critical_window'.
        """
        t_min = t_span[0].item()
        t_max = t_span[-1].item()
        n_eval = self.config.time_search_resolution

        start_times = np.linspace(t_min, t_max * 0.9, n_eval)
        outcomes = np.zeros(n_eval)

        for i, t_start in enumerate(start_times):
            traj = self.simulate_trajectory(
                x0, t_span, drug_id, drug_dose,
                drug_start_time=float(t_start),
            )
            outcomes[i] = float(self._compute_outcome(traj[-1:]))

        # Find the latest time where outcome is still below target
        below_target = outcomes <= target_outcome
        if not below_target.any():
            return {
                "latest_effective_time": None,
                "time_outcome_curve": (start_times.tolist(), outcomes.tolist()),
                "critical_window": None,
                "message": "Intervention at this dose never achieves target.",
            }

        # The critical window is [earliest effective, latest effective]
        effective_times = start_times[below_target]
        earliest = float(effective_times[0])
        latest = float(effective_times[-1])

        return {
            "latest_effective_time": latest,
            "time_outcome_curve": (start_times.tolist(), outcomes.tolist()),
            "critical_window": (earliest, latest),
        }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _build_drug_effect(
        self,
        drug_id: Optional[int],
        dose: float,
    ) -> Callable[[Tensor, float], Tensor]:
        """Build a callable drug effect function g(x, t) -> dx_drug.

        If a drug_encoder is available, uses it. Otherwise, constructs a
        simple linear drug effect: g(x) = dose * W_drug @ x.

        Args:
            drug_id: Drug identifier.
            dose: Drug dosage.

        Returns:
            Callable taking (x, t) and returning drug-induced velocity.
        """
        if drug_id is None or dose == 0.0:
            return lambda x, t: torch.zeros_like(x)

        if self.drug_encoder is not None:
            drug_tensor = torch.tensor([drug_id], device=self.device)
            dose_tensor = torch.tensor([dose], device=self.device, dtype=torch.float32)

            def effect(x: Tensor, t: float) -> Tensor:
                with torch.no_grad():
                    return self.drug_encoder(x, drug_tensor, dose_tensor)
            return effect

        # Fallback: use model's drug_effect if available
        if hasattr(self.model, "drug_effect"):
            def effect(x: Tensor, t: float) -> Tensor:
                return self.model.drug_effect(x, drug_id, dose)
            return effect

        # Minimal fallback: perturbation proportional to dose
        def effect(x: Tensor, t: float) -> Tensor:
            return -dose * 0.1 * x
        return effect

    def _integrate_with_intervention(
        self,
        x0: Tensor,
        t_eval: Tensor,
        drug_effect_fn: Callable,
        t_start: float,
        t_end: float,
    ) -> Tensor:
        """Euler integration of modified ODE with drug intervention.

        dx/dt = f(x, t) + g(x, t) * I(t_start <= t <= t_end)

        Args:
            x0: Initial state (batch, D).
            t_eval: Time points to evaluate.
            drug_effect_fn: Drug effect function g(x, t).
            t_start: Treatment start time.
            t_end: Treatment end time.

        Returns:
            Trajectory tensor (T, batch, D).
        """
        trajectory = [x0]
        x = x0.clone()

        for i in range(1, len(t_eval)):
            t = t_eval[i - 1]
            dt = (t_eval[i] - t_eval[i - 1]).item()

            # Autonomous dynamics
            with torch.no_grad():
                dxdt = self._ode_rhs(x, t)

            # Drug effect (only within treatment window)
            t_val = t.item() if isinstance(t, Tensor) else t
            if t_start <= t_val <= t_end:
                with torch.no_grad():
                    dxdt = dxdt + drug_effect_fn(x, t_val)

            x = x + dt * dxdt
            trajectory.append(x.clone())

        return torch.stack(trajectory)

    def _ode_rhs(self, x: Tensor, t: Tensor) -> Tensor:
        """Evaluate ODE right-hand side."""
        if hasattr(self.model, "ode_func"):
            return self.model.ode_func(t, x)
        raise RuntimeError("Model must expose .ode_func(t, x).")

    def _compute_outcome(self, x: Tensor) -> Tensor:
        """Compute resistance outcome from state."""
        if x.dim() == 3:
            x = x.squeeze(0)
        if hasattr(self.model, "predict"):
            with torch.no_grad():
                return self.model.predict(x).mean()
        if hasattr(self.model, "classifier"):
            with torch.no_grad():
                return torch.sigmoid(self.model.classifier(x)).mean()
        return x.norm(dim=-1).mean()


