"""
Counterfactual trajectory generation and causal effect estimation for ResistanceMap v6.

This module implements:
1. CounterfactualTrajectoryGenerator: Simulate alternative drug interventions on the
   Neural ODE to answer "what would have happened if we used drug X instead of Y?"
2. WhatIfAnalyzer: Broader counterfactual queries including pathway inhibition,
   treatment timing shifts, and drug combination screening.
3. CausalEffectEstimator: Estimate ATE, CATE, and ITE from the learned structural
   causal model (SCM) via do-calculus interventions.

================================================================
DEPRECATION NOTICE — Bug B4 (v19 roadmap)
================================================================
``WhatIfAnalyzer`` (and the ``do_intervention`` method on
``CausalEffectEstimator``) implement "interventions" by *clamping a latent
ODE dimension at integration time*. This is **associational, not
interventional**, because incoming causal edges into the clamped
dimension remain intact — Pearl's do-operator requires *severing* those
edges, which latent clamping does not do.

For interventional counterfactuals (true do-calculus on the biological
graph), use
``resistancemap.mortfm.causal.counterfactual_simulator.CounterfactualSimulator``
(planned in Phase 8). See ``docs/v18_phase_plan/phase_8_counterfactual.md``
§10 for the identifiability discussion.
================================================================

Key innovation: counterfactual trajectories are generated by modifying the ODE
dynamics, not by retraining. The structured Neural ODE allows surgical interventions
on specific biological programs (e.g., set the drug efflux program to zero) while
preserving the learned dynamics of all other programs.

References:
    Pearl, J. (2009). Causality: Models, Reasoning, and Inference. Cambridge Univ Press.
    Shalit, U. et al. (2017). Estimating individual treatment effect. ICML.
    Bica, I. et al. (2020). Estimating counterfactual treatment outcomes over time. NeurIPS.
    De Brouwer, E. et al. (2019). GRU-ODE-Bayes. NeurIPS.
    Seedat, N. et al. (2022). Continuous-time modeling of counterfactual outcomes. ICML.
"""

