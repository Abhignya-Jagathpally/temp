class WhatIfAnalyzer:
    """ASSOCIATIONAL ONLY — not a do-calculus implementation.

    Broader counterfactual reasoning over the Neural ODE.

    Supports:
    - Pathway inhibition: "What if we knock out the PI3K/AKT pathway?"
    - Treatment timing: "What if we started treatment 2 months earlier?"
    - Drug combinations: "What combination of drugs achieves synergy?"

    Each query modifies the ODE dynamics by *clamping a latent state
    dimension* at integration time. This is **associational** (effectively
    a covariate intervention on the latent trajectory) and is NOT a
    Pearl-do operation, because incoming causal edges into the clamped
    dimension remain intact rather than being severed.

    For real do-calculus counterfactuals on the biological graph, use
    ``resistancemap.mortfm.causal.counterfactual_simulator.CounterfactualSimulator``
    (planned in Phase 8). See ``docs/v18_phase_plan/phase_8_counterfactual.md``
    §10 for the identifiability discussion.

    Args:
        model: ResistanceMap Neural ODE.
        program_names: Names of the biological programs (latent dimensions).
        cf_generator: CounterfactualTrajectoryGenerator for simulation.
        config: CounterfactualConfig.
    """

    def __init__(
        self,
        model: nn.Module,
        program_names: List[str],
        cf_generator: Optional[CounterfactualTrajectoryGenerator] = None,
        config: Optional[CounterfactualConfig] = None,
    ) -> None:
        warnings.warn(_LATENT_CLAMP_WARNING, DeprecationWarning, stacklevel=2)
        self.model = model
        self.program_names = program_names
        self.program_to_idx = {name: i for i, name in enumerate(program_names)}
        self.config = config or CounterfactualConfig()
        self.device = torch.device(self.config.device)

        if cf_generator is not None:
            self.cf_gen = cf_generator
        else:
            self.cf_gen = CounterfactualTrajectoryGenerator(model, config=self.config)

    def inhibit_pathway(
        self,
        x0: Tensor,
        t_span: Tensor,
        pathway_name: str,
        inhibition_strength: float = 1.0,
    ) -> Dict[str, Any]:
        """Simulate trajectory with a specific pathway/program inhibited.

        Sets the corresponding dimension of the ODE state to zero (full
        inhibition) or reduces it (partial inhibition) at each integration step.

        This corresponds to a perfect pathway inhibitor drug with instantaneous
        action: do(program_k = 0).

        Args:
            x0: Initial state.
            t_span: Time span.
            pathway_name: Name of the biological program to inhibit.
            inhibition_strength: 0.0 = no inhibition, 1.0 = full knockout.

        Returns:
            Dict with 'inhibited_trajectory', 'baseline_trajectory',
            'outcome_change', 'program_idx'.
        """
        warnings.warn(_LATENT_CLAMP_WARNING, DeprecationWarning, stacklevel=2)
        if pathway_name not in self.program_to_idx:
            raise ValueError(
                f"Unknown program: {pathway_name}. "
                f"Available: {list(self.program_to_idx.keys())}"
            )

        prog_idx = self.program_to_idx[pathway_name]

        if x0.dim() == 1:
            x0 = x0.unsqueeze(0)
        x0 = x0.to(self.device)
        t_span = t_span.to(self.device)

        # Baseline trajectory (no inhibition)
        with torch.no_grad():
            baseline_traj = self._solve_ode(x0, t_span)

        # Inhibited trajectory: clamp program dimension at each step
        inhibited_traj = [x0.clone()]
        x = x0.clone()
        for i in range(1, len(t_span)):
            dt = (t_span[i] - t_span[i - 1]).item()
            with torch.no_grad():
                dxdt = self._ode_rhs(x, t_span[i - 1])
            x = x + dt * dxdt
            # Apply inhibition: reduce the target program dimension
            x_new = x.clone()
            x_new[:, prog_idx] = x[:, prog_idx] * (1.0 - inhibition_strength)
            x = x_new
            inhibited_traj.append(x.clone())
        inhibited_traj = torch.stack(inhibited_traj)

        # Compute outcomes
        baseline_out = float(self._compute_outcome(baseline_traj[-1:]))
        inhibited_out = float(self._compute_outcome(inhibited_traj[-1:]))

        return {
            "inhibited_trajectory": inhibited_traj.squeeze(1).detach().cpu().numpy(),
            "baseline_trajectory": baseline_traj.squeeze(1).detach().cpu().numpy(),
            "baseline_outcome": baseline_out,
            "inhibited_outcome": inhibited_out,
            "outcome_change": inhibited_out - baseline_out,
            "program_idx": prog_idx,
            "pathway_name": pathway_name,
            "inhibition_strength": inhibition_strength,
        }

    def shift_treatment_timing(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_id: int,
        drug_dose: float,
        original_start: float,
        time_shifts: List[float],
    ) -> Dict[str, Any]:
        """Simulate trajectories with treatment starting at different times.

        Answers: "What if we had started treatment N months earlier/later?"

        Args:
            x0: Initial state.
            t_span: Time span.
            drug_id: Drug identifier.
            drug_dose: Drug dosage.
            original_start: Original treatment start time.
            time_shifts: List of time deltas (negative = earlier, positive = later).

        Returns:
            Dict mapping shift label -> trajectory and outcome.
        """
        results = {}

        for shift in time_shifts:
            new_start = max(original_start + shift, t_span[0].item())
            label = f"shift_{shift:+.1f}"

            traj = self.cf_gen.simulate_trajectory(
                x0, t_span, drug_id, drug_dose,
                drug_start_time=new_start,
            )
            outcome = float(self._compute_outcome(traj[-1:]))

            results[label] = {
                "trajectory": traj.numpy(),
                "outcome": outcome,
                "treatment_start": new_start,
                "time_shift": shift,
            }

        return results

    def screen_drug_combinations(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_ids: List[int],
        drug_doses: List[float],
        drug_names: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Screen drug pairs/triplets for synergistic effects.

        For each pair of drugs, simulate the combined trajectory and compare
        to individual drug trajectories. Synergy is defined using Bliss
        independence:
            synergy = E_AB - E_A * E_B
        where E is the efficacy (reduction in resistance outcome).

        Args:
            x0: Initial state.
            t_span: Time span.
            drug_ids: List of drug identifiers to screen.
            drug_doses: Corresponding doses.
            drug_names: Optional human-readable names.

        Returns:
            Dict with 'individual_outcomes', 'combination_outcomes',
            'synergy_scores', 'best_combination'.
        """
        n_drugs = len(drug_ids)
        if drug_names is None:
            drug_names = [f"drug_{d}" for d in drug_ids]

        # No-treatment baseline
        baseline_traj = self.cf_gen.simulate_trajectory(x0, t_span)
        baseline_outcome = float(self._compute_outcome(baseline_traj[-1:]))

        # Individual drug outcomes
        individual = {}
        for drug_id, dose, name in zip(drug_ids, drug_doses, drug_names):
            traj = self.cf_gen.simulate_trajectory(x0, t_span, drug_id, dose)
            outcome = float(self._compute_outcome(traj[-1:]))
            efficacy = max(0, baseline_outcome - outcome) / max(baseline_outcome, 1e-8)
            individual[name] = {"outcome": outcome, "efficacy": efficacy}

        # Drug pair combinations
        combination_outcomes = {}
        synergy_scores = {}

        max_combo = min(self.config.combination_max_drugs, n_drugs)
        from itertools import combinations

        for r in range(2, max_combo + 1):
            for combo_idx in combinations(range(n_drugs), r):
                combo_name = " + ".join(drug_names[i] for i in combo_idx)

                # Simulate combined effect by summing drug effects
                # This is done by sequential simulation with cumulative interventions
                traj = self._simulate_combination(
                    x0, t_span,
                    [drug_ids[i] for i in combo_idx],
                    [drug_doses[i] for i in combo_idx],
                )
                outcome = float(self._compute_outcome(traj[-1:]))
                combo_efficacy = max(0, baseline_outcome - outcome) / max(baseline_outcome, 1e-8)

                combination_outcomes[combo_name] = {
                    "outcome": outcome,
                    "efficacy": combo_efficacy,
                }

                # Bliss independence for synergy
                indiv_efficacies = [individual[drug_names[i]]["efficacy"] for i in combo_idx]
                expected_indep = 1.0
                for e in indiv_efficacies:
                    expected_indep *= (1.0 - e)
                expected_efficacy = 1.0 - expected_indep

                synergy = combo_efficacy - expected_efficacy
                synergy_scores[combo_name] = synergy

        # Find best combination
        if synergy_scores:
            best = max(synergy_scores, key=synergy_scores.get)
        else:
            best = None

        return {
            "baseline_outcome": baseline_outcome,
            "individual_outcomes": individual,
            "combination_outcomes": combination_outcomes,
            "synergy_scores": synergy_scores,
            "best_combination": best,
        }

    def _simulate_combination(
        self,
        x0: Tensor,
        t_span: Tensor,
        drug_ids: List[int],
        drug_doses: List[float],
    ) -> Tensor:
        """Simulate trajectory under multiple concurrent drugs.

        Sums the drug effects from each drug at each integration step.
        """
        if x0.dim() == 1:
            x0 = x0.unsqueeze(0)
        x0 = x0.to(self.device)
        t_span = t_span.to(self.device)

        drug_effects = [
            self.cf_gen._build_drug_effect(did, dose)
            for did, dose in zip(drug_ids, drug_doses)
        ]

        trajectory = [x0]
        x = x0.clone()
        for i in range(1, len(t_span)):
            dt = (t_span[i] - t_span[i - 1]).item()
            with torch.no_grad():
                dxdt = self._ode_rhs(x, t_span[i - 1])
                for eff in drug_effects:
                    dxdt = dxdt + eff(x, t_span[i - 1].item())
            x = x + dt * dxdt
            trajectory.append(x.clone())

        return torch.stack(trajectory).detach().cpu()

    # ------------------------------------------------------------------
    # Shared helpers
    # ------------------------------------------------------------------

    def _solve_ode(self, x0: Tensor, t_eval: Tensor) -> Tensor:
        if hasattr(self.model, "solve"):
            return self.model.solve(x0, t_eval)
        try:
            from torchdiffeq import odeint
            return odeint(self.model.ode_func, x0, t_eval)
        except ImportError:
            # Euler fallback
            traj = [x0]
            x = x0
            for i in range(1, len(t_eval)):
                dt = (t_eval[i] - t_eval[i - 1]).item()
                x = x + dt * self._ode_rhs(x, t_eval[i - 1])
                traj.append(x)
            return torch.stack(traj)

    def _ode_rhs(self, x: Tensor, t: Tensor) -> Tensor:
        if hasattr(self.model, "ode_func"):
            return self.model.ode_func(t, x)
        raise RuntimeError("Model must expose .ode_func(t, x).")

    def _compute_outcome(self, x: Tensor) -> Tensor:
        if x.dim() == 3:
            x = x.squeeze(0)
        if hasattr(self.model, "predict"):
            with torch.no_grad():
                return self.model.predict(x).mean()
        if hasattr(self.model, "classifier"):
            with torch.no_grad():
                return torch.sigmoid(self.model.classifier(x)).mean()
        return x.norm(dim=-1).mean()


