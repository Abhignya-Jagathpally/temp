@dataclass
class CounterfactualConfig:
    """Configuration for counterfactual analysis.

    Attributes:
        n_trajectory_samples: Number of stochastic trajectory samples for
            uncertainty quantification.
        ode_solver_steps: Number of integration steps for the ODE solver.
        min_intervention_strength: Minimum drug dose to consider.
        max_intervention_strength: Maximum drug dose to consider.
        dose_search_resolution: Number of dose levels to try in dose-response.
        time_search_resolution: Number of time points for optimal timing search.
        convergence_threshold: Threshold for determining trajectory convergence
            to an attractor (resistant vs sensitive).
        combination_max_drugs: Maximum number of drugs in combination search.
        device: Torch device string.
    """
    n_trajectory_samples: int = 100
    ode_solver_steps: int = 200
    min_intervention_strength: float = 0.0
    max_intervention_strength: float = 10.0
    dose_search_resolution: int = 50
    time_search_resolution: int = 50
    convergence_threshold: float = 0.1
    combination_max_drugs: int = 3
    device: str = "cpu"


